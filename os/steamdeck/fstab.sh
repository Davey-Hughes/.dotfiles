#!/bin/bash
#
# Puts the mounts in ./fstab into /etc/fstab.
#
#   ./fstab.sh            apply: show the diff, write it, reload, mount
#   ./fstab.sh --print    print what /etc/fstab would become; change nothing
#
# Safe to re-run. The entries go in as one marked block, and every run replaces
# that block rather than adding to the file: a second run changes nothing, and
# an entry edited in or dropped from ./fstab is edited or dropped there too.
#
# This used to be `sudo tee -a /etc/fstab < ./fstab`, which is fine for a script
# run once per machine and wrong the second time -- every share listed twice.
# "Once per machine" stopped being true: each SteamOS update puts the image's
# stock /etc/fstab back, so this is now part of recovering from one.
#
# --print also takes a DEST and a SRC to read in place of /etc/fstab and
# ./fstab, which is how tests/test-steamdeck-fstab.sh drives the rewrite against
# scratch files. Applying takes no arguments at all: it only writes /etc/fstab.

set -u

SCRIPTDIR=$(dirname "$(readlink -f "$0")")
DEST=/etc/fstab
SRC=$SCRIPTDIR/fstab

# Matched as whole lines. Rewording either one orphans the block an earlier run
# wrote; the mount-point rule in render() still keeps that from duplicating a
# share, but the old pair of comments is left behind.
BEGIN='# BEGIN dotfiles os/steamdeck/fstab -- generated by fstab.sh, edit the source instead'
END='# END dotfiles os/steamdeck/fstab'

# Prints what <dest> should become: everything in it that is not ours, then our
# block. Reads both files and writes neither.
render() { # render <dest> <src>
  local f
  for f in "$1" "$2"; do
    [ -r "$f" ] || { echo "ERROR: cannot read $f" >&2; return 1; }
  done

  awk -v begin="$BEGIN" -v end="$END" '
    # The source: remember each entry and the mount point it claims.
    #
    # Told apart by FILENAME, not by the usual NR == FNR. That idiom is also
    # true of the SECOND file whenever the first is empty, which would file
    # every line of /etc/fstab as one of ours -- written into the block now and
    # deleted with it on the next run.
    FILENAME == ARGV[1] {
      if ($0 !~ /^[[:space:]]*(#|$)/) { entry[++n] = $0; ours[$2] = 1 }
      next
    }

    $0 == begin { inblock = 1; next }
    $0 == end   { inblock = 0; next }
    inblock     { next }

    # An entry for one of our mount points sitting outside the block. The old
    # append left these behind, and keeping one would mount the share twice.
    NF >= 2 && $0 !~ /^[[:space:]]*#/ && ($2 in ours) { next }

    { keep[++k] = $0 }

    END {
      # A BEGIN with no END means the rule above swallowed the rest of the
      # file. Refuse rather than hand back an fstab with its tail missing.
      if (inblock) {
        print "ERROR: \"" begin "\" has no matching END line" > "/dev/stderr"
        exit 1
      }

      # Trailing blank lines go, or the separator below would add one per run.
      while (k && keep[k] ~ /^[[:space:]]*$/) k--
      for (i = 1; i <= k; i++) print keep[i]

      # No entries, no block: emptying ./fstab removes the mounts cleanly.
      if (n) {
        print ""
        print begin
        for (i = 1; i <= n; i++) print entry[i]
        print end
      }
    }
  ' "$2" "$1"
}

if [ $# -gt 0 ]; then
  if [ "$1" != --print ] || [ $# -gt 3 ]; then
    echo "usage: $0 [--print [DEST [SRC]]]" >&2
    exit 1
  fi
  render "${2:-$DEST}" "${3:-$SRC}"
  exit
fi

new=$(mktemp) || exit 1
trap 'rm -f -- "$new"' EXIT

render "$DEST" "$SRC" > "$new" || exit 1

if cmp -s "$DEST" "$new"; then
  echo "$DEST already has the current entries; nothing to do."
  exit 0
fi

diff -u --label "$DEST" --label "$DEST (new)" "$DEST" "$new"

# Copied in beside the target and renamed over it. A rename is atomic, so
# nothing ever reads a half-written fstab. (`sudo cat "$new" > /etc/fstab` would
# not get even that far: the shell opens the redirect itself, before sudo runs,
# as the invoking user.)
sudo install -m 644 "$new" "$DEST.new" || exit 1
sudo mv "$DEST.new" "$DEST" || exit 1

sudo systemctl daemon-reload
sudo mount -a
